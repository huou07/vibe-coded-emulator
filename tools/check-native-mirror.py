#!/usr/bin/env python3
"""Fail when the Android app's committed web assets drift from their sources.

The Android build serves the app's UI straight out of Android assets:
`An3SecureWebViewClient` installs a `WebViewAssetLoader.AssetsPathHandler` for
`/`, so `gen/android/app/src/main/assets/index.html`, `native-*.js` and
`static/**` are the real Android UI. Unlike the desktop target, which embeds
`native-offline/dist` with `include_dir!` (see `src-tauri/src/lib.rs`), mobile
reads the committed mirror. Nothing in the build regenerates that mirror: no
script copies `dist/` or `static/` into `gen/android/app/src/main/assets/`, and
Tauri's own Android `.gitignore` only covers `/src/main/assets/tauri.conf.json`.

That makes the mirror a second source of truth for the same files, kept in sync
by hand. It silently rotted: at `d94a8b7` the committed mirror shipped
`static/site.css` and `static/theme-violet.css` from September while the Web and
desktop sources had moved on, and `tools/build-public-snapshot.sh` keeps the
mirror's `site.css` verbatim in the public candidate, so the stale stylesheet was
publishable. This check is what makes AGENTS.md's rule -- "a `static/` edit is
simultaneously a Web change *and* an unreleased native change" -- enforced
instead of remembered.

Some mirror content is deliberately not a copy and is declared below with its
reason, so a skip is never silent and an undeclared new file is a finding.

Exit status: 0 clean, 1 findings, 2 the check could not run (fail closed).
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIRROR = ROOT / "native-offline/src-tauri/gen/android/app/src/main/assets"

# Mirror content that is deliberately not a copy of a repository source. Each
# entry is (prefix or exact relative path, reason). These are reported on every
# run so the gate publishes what it did not compare.
NOT_CHECKED: tuple[tuple[str, str], ...] = (
    (
        "emulatorjs/",
        "the vendored locked web runtime; its bytes are pinned and verified "
        "against native-offline/shared/web-runtime-lock.json by prepare-web.mjs "
        "and tests/test_linux_native_runtime.py, not against a source copy",
    ),
    (
        "native-core-licenses/",
        "generated by native-offline/scripts/build-android-runtime.sh from "
        "native-offline/vendor/**, which is the authority for those notices",
    ),
    (
        "THIRD_PARTY_NOTICES.md",
        "the Android app's own native-core notices ('EmulatorRust native core "
        "notices'), a distinct document from the repository root's "
        "THIRD_PARTY_NOTICES.md, not a copy of it",
    ),
    (
        "tauri.conf.json",
        "written into the Android project by Tauri itself and already ignored by "
        "gen/android/app/.gitignore",
    ),
)


def mapped_sources() -> list[tuple[Path, Path]]:
    """Return (source, mirror) pairs for every file the mirror must copy."""
    pairs: list[tuple[Path, Path]] = []

    static = ROOT / "static"
    for base, _dirs, names in os.walk(static):
        for name in names:
            source = Path(base) / name
            pairs.append((source, MIRROR / "static" / source.relative_to(static)))

    web = ROOT / "native-offline/web"
    for name in sorted(os.listdir(web)) if web.is_dir() else []:
        source = web / name
        if source.is_file():
            pairs.append((source, MIRROR / name))

    pairs.append((ROOT / "LICENSE", MIRROR / "LICENSE"))
    pairs.append((
        ROOT / "native-offline/shared/native-layout-schema.json",
        MIRROR / "native-layout-schema.json",
    ))
    return pairs


def declared(mirror_rel: str) -> bool:
    return any(
        mirror_rel == entry or mirror_rel.startswith(entry)
        for entry, _reason in NOT_CHECKED
    )


def describe_difference(source: Path, mirror: Path) -> str:
    """One line naming the drift, with a first differing line when it is text."""
    try:
        source_text = source.read_text(encoding="utf-8")
        mirror_text = mirror.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return (
            f"binary content differs "
            f"(source {source.stat().st_size} bytes, mirror {mirror.stat().st_size} bytes)"
        )
    for number, (left, right) in enumerate(
        zip(source_text.splitlines(), mirror_text.splitlines()), start=1
    ):
        if left != right:
            return (
                f"first differing line {number}: "
                f"source {left.strip()[:60]!r} vs mirror {right.strip()[:60]!r}"
            )
    return (
        f"identical lines but different length "
        f"(source {len(source_text.splitlines())} lines, "
        f"mirror {len(mirror_text.splitlines())} lines)"
    )


def main() -> int:
    if not MIRROR.is_dir():
        print(
            f"Native web-asset mirror check cannot run: {MIRROR} is not a directory",
            file=sys.stderr,
        )
        return 2

    findings: list[str] = []
    pairs = mapped_sources()
    checked: set[str] = set()

    for source, mirror in pairs:
        mirror_rel = mirror.relative_to(MIRROR).as_posix()
        checked.add(mirror_rel)
        label = source.relative_to(ROOT).as_posix()
        if not source.is_file():
            findings.append(
                f"missing source {label}: the mirror keeps {mirror_rel}, so the "
                f"source must exist and be the copy it is synced from"
            )
            continue
        if not mirror.is_file():
            findings.append(
                f"missing mirror file {mirror_rel}: copy {label} into the Android "
                f"assets, or declare it in NOT_CHECKED with a reason"
            )
            continue
        if source.read_bytes() != mirror.read_bytes():
            findings.append(
                f"drifted mirror file {mirror_rel}: {describe_difference(source, mirror)} "
                f"-- re-copy {label}; never edit the mirror by hand"
            )

    for base, _dirs, names in os.walk(MIRROR):
        for name in names:
            mirror_rel = (Path(base) / name).relative_to(MIRROR).as_posix()
            if mirror_rel in checked or declared(mirror_rel):
                continue
            findings.append(
                f"undeclared mirror file {mirror_rel}: give it a source mapping in "
                f"mapped_sources() or a guarded reason in NOT_CHECKED"
            )

    for entry, reason in NOT_CHECKED:
        print(f"NATIVE_MIRROR_SKIP {entry}|{reason}")

    if findings:
        print("Native web-asset mirror check FAILED:\n", file=sys.stderr)
        for finding in findings:
            print(f"  {finding}", file=sys.stderr)
        print(
            f"\n{len(findings)} finding(s) across {len(checked)} compared file(s).\n"
            "The Android app is served from this mirror, so drift is a shipped "
            "stylesheet or script, not a cosmetic difference. Re-copy from the "
            "named source; do not silence the check.",
            file=sys.stderr,
        )
        print("NATIVE_MIRROR=FAIL")
        return 1

    print(
        f"Native web-asset mirror check: clean "
        f"({len(checked)} file(s) identical to their sources, "
        f"{len(NOT_CHECKED)} declared non-copy entr(ies))"
    )
    print("NATIVE_MIRROR=PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
